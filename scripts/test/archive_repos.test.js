import { describe, it, before, after } from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, readFile, writeFile, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';

import {
  ISSUE_TITLE,
  OSPO_ARCHIVE_ISSUE_TITLE,
  buildCatalogue,
  buildJsonResults,
  buildIssueBody,
  buildOspoArchiveIssueBody,
  loadConfig,
  processRepos,
  run,
} from '../archive_repos.js';
import { createPlan } from '../lib/plan.js';
import { createFakeGitHub, notFound } from './helpers/fake_github.js';
import { createMemoryLogger } from './helpers/memory_logger.js';

const org = 'test-org';
const NOW = new Date('2026-06-01T00:00:00Z');
// warn_after "2 years" → stale if pushed before 2024-06-01
// grace_period "40 days" → warning issues created before 2026-04-22 have expired
const staleCutoff = new Date('2024-06-01T00:00:00Z');
const graceCutoff = new Date('2026-04-22T00:00:00Z');

const warning = (number, createdAt) => ({ number, title: ISSUE_TITLE, created_at: createdAt, state: 'open' });

let tmpDir;
before(async () => { tmpDir = await mkdtemp(path.join(tmpdir(), 'archive-test-')); });
after(async () => { await rm(tmpDir, { recursive: true }); });

async function writeConfig(name, lines) {
  const file = path.join(tmpDir, name);
  await writeFile(file, lines.join('\n'));
  return file;
}

// ── Issue bodies ─────────────────────────────────────────────────────────────

describe('buildIssueBody', () => {
  it('mentions the grace period and the empty-commit hint', () => {
    const body = buildIssueBody('40 days');
    assert.match(body, /within the next 40 days/);
    assert.match(body, /git commit --allow-empty/);
  });
});

describe('buildOspoArchiveIssueBody', () => {
  it('has the header, one row per repo and the attribution line', () => {
    const body = buildOspoArchiveIssueBody([{ repo: 'a', daysLeft: 3 }, { repo: 'b', daysLeft: 10 }]);
    assert.ok(body.startsWith('## Stale Repository Summary'));
    assert.ok(body.includes('| Repository | Days until archival |'));
    assert.ok(body.includes('| a | 3 days |'));
    assert.ok(body.includes('| b | 10 days |'));
    assert.ok(body.includes('_This issue was automatically generated by the OSPO archive script._'));
  });
});

// ── loadConfig ───────────────────────────────────────────────────────────────

describe('loadConfig', () => {
  it('parses a valid config', async () => {
    const file = await writeConfig('valid.yaml', ['excluded_repos: [.github, ospo]', 'warn_after: "2 years"', 'grace_period: "40 days"']);
    const cfg = await loadConfig(file);
    assert.equal(cfg.warn_after, '2 years');
    assert.equal(cfg.grace_period, '40 days');
    assert.deepEqual(cfg.excluded_repos, ['.github', 'ospo']);
  });

  it('defaults excluded_repos to an empty array', async () => {
    const file = await writeConfig('no-excluded.yaml', ['warn_after: "1 year"', 'grace_period: "30 days"']);
    assert.deepEqual((await loadConfig(file)).excluded_repos, []);
  });

  for (const [name, lines, error] of [
    ['missing warn_after', ['grace_period: "40 days"'], /warn_after/],
    ['missing grace_period', ['warn_after: "2 years"'], /grace_period/],
    ['invalid warn_after', ['warn_after: "last week"', 'grace_period: "40 days"'], /Invalid relative date/],
    ['invalid grace_period', ['warn_after: "2 years"', 'grace_period: "soon"'], /Invalid relative date/],
    ['empty file', [''], /warn_after/],
  ]) {
    it(`throws on ${name}`, async () => {
      const file = await writeConfig(`${name.replace(/ /g, '-')}.yaml`, lines);
      await assert.rejects(() => loadConfig(file), error);
    });
  }
});

// ── processRepos ─────────────────────────────────────────────────────────────

describe('processRepos', () => {
  async function process(repos, issues = {}, { dryRun = false, debug = false } = {}) {
    const gh = createFakeGitHub({ repos, issues, now: () => NOW });
    const logger = createMemoryLogger({ debug });
    const plan = createPlan({ dryRun, logger });
    const result = await processRepos({ gh, plan, logger, org, repos, staleCutoff, graceCutoff, gracePeriod: '40 days', now: NOW });
    return { gh, plan, logger, result };
  }

  it('creates a warning issue for a stale repo without one, but does not archive it', async () => {
    const { gh, logger, result } = await process([{ name: 'old', pushed_at: '2023-06-01T00:00:00Z' }]);
    const [created] = gh.state.issues.old;
    assert.equal(created.title, ISSUE_TITLE);
    assert.match(created.body, /40 days/);
    assert.equal(gh.callsTo('archiveRepo').length, 0);
    assert.deepEqual(result.upcoming, [{ repo: 'old', daysLeft: 40 }]);
    assert.match(logger.output(), /test-org\/old is stale\.\n  Created warning issue\.\n  test-org\/old has remaining grace period\./);
  });

  it('keeps an unexpired warning and reports the days left', async () => {
    const { gh, result } = await process(
      [{ name: 'stale', pushed_at: '2023-06-01T00:00:00Z' }],
      { stale: [warning(12, '2026-05-06T00:00:00Z')] },
    );
    assert.deepEqual(gh.writes(), []);
    assert.deepEqual(result.upcoming, [{ repo: 'stale', daysLeft: 14 }]);
  });

  it('archives a stale repo whose warning is past the grace period', async () => {
    const { gh, logger } = await process(
      [{ name: 'dead', pushed_at: '2022-01-01T00:00:00Z' }],
      { dead: [warning(8, '2026-01-15T00:00:00Z')] },
    );
    assert.equal(gh.state.repos[0].archived, true);
    assert.match(logger.output(), /Archived the repository 'test-org\/dead'\./);
  });

  it('closes the warning when the repo became active again', async () => {
    const { gh, logger } = await process(
      [{ name: 'alive', pushed_at: '2026-03-01T00:00:00Z' }],
      { alive: [warning(15, '2026-02-01T00:00:00Z')] },
    );
    assert.equal(gh.state.issues.alive[0].state, 'closed');
    assert.equal(gh.callsTo('commentIssue').length, 0, 'warning issues are closed without a comment');
    assert.match(logger.output(), /Closed the existing issue in the repository 'test-org\/alive'\./);
  });

  it('ignores pull requests with the warning title', async () => {
    const { gh } = await process(
      [{ name: 'alive', pushed_at: '2026-03-01T00:00:00Z' }],
      { alive: [{ ...warning(3, '2026-02-01T00:00:00Z'), pull_request: {} }] },
    );
    assert.deepEqual(gh.writes(), []);
  });

  it('skips repos without any push', async () => {
    const { gh, logger } = await process([{ name: 'empty', pushed_at: null }], {}, { debug: true });
    assert.equal(gh.calls.length, 0);
    assert.match(logger.output(), /test-org\/empty — skipped \(no push activity yet\)/);
  });

  it('dry-run plans every change but makes none', async () => {
    const { gh, plan } = await process(
      [
        { name: 'new-stale', pushed_at: '2023-01-01T00:00:00Z' },
        { name: 'expired', pushed_at: '2022-01-01T00:00:00Z' },
        { name: 'revived', pushed_at: '2026-05-01T00:00:00Z' },
      ],
      { expired: [warning(1, '2026-01-01T00:00:00Z')], revived: [warning(2, '2026-01-01T00:00:00Z')] },
      { dryRun: true },
    );
    assert.deepEqual(gh.writes(), []);
    assert.deepEqual(plan.planned, [
      "Would create an issue for 'test-org/new-stale'.",
      "Would archive repository 'test-org/expired'.",
      "Would close the existing issue in 'test-org/revived'.",
    ]);
  });

  it('dry-run never archives a repo whose warning would only be created now', async () => {
    const { plan } = await process([{ name: 'old', pushed_at: '2020-01-01T00:00:00Z' }], {}, { dryRun: true });
    assert.deepEqual(plan.planned, ["Would create an issue for 'test-org/old'."]);
  });

  it('sorts upcoming by days left and excludes active and archived repos', async () => {
    const { result } = await process(
      [
        { name: 'b', pushed_at: '2023-01-01T00:00:00Z' },
        { name: 'a', pushed_at: '2023-01-01T00:00:00Z' },
        { name: 'gone', pushed_at: '2022-01-01T00:00:00Z' },
        { name: 'fresh', pushed_at: '2026-05-01T00:00:00Z' },
      ],
      {
        b: [warning(1, '2026-05-20T00:00:00Z')],
        a: [warning(2, '2026-04-25T00:00:00Z')],
        gone: [warning(3, '2026-01-01T00:00:00Z')],
      },
    );
    assert.deepEqual(result.upcoming, [{ repo: 'a', daysLeft: 3 }, { repo: 'b', daysLeft: 28 }]);
  });

  it('returns the top three next warnings, soonest first, without repos that have a warning', async () => {
    const { result } = await process(
      [
        { name: 'r1', pushed_at: '2025-01-01T00:00:00Z' },
        { name: 'r2', pushed_at: '2024-07-01T00:00:00Z' },
        { name: 'r3', pushed_at: '2026-01-01T00:00:00Z' },
        { name: 'r4', pushed_at: '2024-06-11T00:00:00Z' },
        { name: 'r5', pushed_at: '2024-06-02T00:00:00Z' },
      ],
      { r5: [warning(9, '2026-01-01T00:00:00Z')] },
    );
    assert.deepEqual(result.nextWarnings, [
      { repo: 'r4', daysUntilWarning: 10 },
      { repo: 'r2', daysUntilWarning: 30 },
      { repo: 'r1', daysUntilWarning: 214 },
    ]);
  });
});

// ── run ──────────────────────────────────────────────────────────────────────

describe('run', () => {
  let configPath;
  before(async () => {
    configPath = await writeConfig('run.yaml', ['warn_after: "2 years"', 'grace_period: "40 days"', 'excluded_repos: [ospo]']);
  });

  const repos = [
    { name: 'ospo', pushed_at: '2020-01-01T00:00:00Z' },
    { name: 'zeta-stale', pushed_at: '2023-01-01T00:00:00Z' },
    { name: 'alpha-expired', pushed_at: '2022-01-01T00:00:00Z' },
    { name: 'beta-active', pushed_at: '2026-01-01T00:00:00Z' },
    { name: 'old-archived', pushed_at: '2019-01-01T00:00:00Z', archived: true },
  ];
  const issues = { 'alpha-expired': [warning(4, '2026-01-01T00:00:00Z')] };

  async function runArchive(argv, fakeOptions = {}, { debug = false, env } = {}) {
    const gh = createFakeGitHub({ repos, issues, now: () => NOW, ...fakeOptions });
    const logger = createMemoryLogger({ debug });
    const code = await run({ argv: ['--org', org, '--config', configPath, ...argv], github: gh, logger, now: NOW, env });
    return { gh, logger, code };
  }

  it('dry-run prints the plan, upcoming archival and next warnings', async t => {
    const { gh, logger, code } = await runArchive(['--dry-run']);
    assert.equal(code, 0);
    assert.deepEqual(gh.writes(), []);
    t.assert.snapshot(logger.output());
  });

  it('live run archives, warns, and creates the OSPO summary issue', async () => {
    const { gh, logger } = await runArchive([]);
    assert.equal(gh.state.repos.find(r => r.name === 'alpha-expired').archived, true);
    assert.equal(gh.state.issues['zeta-stale'][0].title, ISSUE_TITLE);
    const [summary] = gh.state.issues.ospo;
    assert.equal(summary.title, OSPO_ARCHIVE_ISSUE_TITLE);
    assert.match(summary.body, /\| zeta-stale \| 40 days \|/);
    assert.equal(gh.callsTo('listOpenIssues').some(c => c.args[1] === 'old-archived'), false, 'archived repos are skipped');
    assert.match(logger.output(), /Created OSPO summary issue in 'test-org\/ospo'\./);
  });

  it('updates an existing OSPO summary issue', async () => {
    const { gh, logger } = await runArchive([], {
      issues: { ...issues, ospo: [{ number: 50, title: OSPO_ARCHIVE_ISSUE_TITLE, body: 'old', state: 'open' }] },
    });
    assert.match(gh.state.issues.ospo[0].body, /zeta-stale/);
    assert.match(logger.output(), /Updated OSPO summary issue #50 in 'test-org\/ospo'\./);
  });

  it('closes the OSPO summary issue when nothing is pending and prints "No changes needed."', async () => {
    const { gh, logger } = await runArchive([], {
      repos: [{ name: 'fresh', pushed_at: '2026-05-01T00:00:00Z' }],
      issues: { ospo: [{ number: 50, title: OSPO_ARCHIVE_ISSUE_TITLE, state: 'open' }] },
    });
    assert.equal(gh.state.issues.ospo[0].state, 'closed');
    assert.match(logger.output(), /Closed OSPO summary issue #50 in 'test-org\/ospo'\.\n\nNext warning issues \(top 3\):\n  fresh  in 699 days\n\nNo changes needed\.\n$/);
  });

  it('dry-run plans the OSPO summary update and close', async () => {
    const withSummary = { ospo: [{ number: 50, title: OSPO_ARCHIVE_ISSUE_TITLE, state: 'open' }] };
    const update = await runArchive(['--dry-run'], { issues: { ...issues, ...withSummary } });
    assert.match(update.logger.output(), /Would update OSPO summary issue #50 in 'test-org\/ospo'\./);
    const close = await runArchive(['--dry-run'], { repos: [], issues: withSummary });
    assert.match(close.logger.output(), /Would close OSPO summary issue #50 in 'test-org\/ospo'\./);
  });

  it('prints cutoffs and the repo selection with --debug', async () => {
    const { logger } = await runArchive(['--dry-run', '--debug'], {}, { debug: true });
    const output = logger.output();
    assert.match(output, /Stale period cutoff: 2024-06-01T00:00:00\.000Z/);
    assert.match(output, /Grace period cutoff: 2026-04-22T00:00:00\.000Z/);
    assert.match(output, /Repos to process: alpha-expired, beta-active, zeta-stale/);
    assert.match(output, /Excluded repos: ospo/);
  });

  it('fails with a clear error when the ospo repository does not exist', async () => {
    const failures = { listOpenIssues: (o, repo) => repo === 'ospo' && notFound() };
    await assert.rejects(
      () => runArchive([], { failures }),
      { name: 'Error', message: "repository 'test-org/ospo' not found. The OSPO summary issue cannot be managed without this repository." },
    );
  });

  it('rejects a missing --org and a missing token', async () => {
    await assert.rejects(() => run({ argv: [] }), /--org is required/);
    await assert.rejects(() => run({ argv: ['--org', org], env: {} }), /GITHUB_TOKEN/);
  });

  it('--json writes both checks per evaluated repo and lists skipped repos', async t => {
    const file = path.join(tmpDir, 'out', 'archive_repos.json');
    const { logger } = await runArchive(['--json', file], { repos: [...repos, { name: 'empty', pushed_at: null }] }, {
      env: { GITHUB_SHA: 'abc123' },
    });
    assert.match(logger.output(), /\nJSON written to .*archive_repos\.json\n$/);
    const doc = JSON.parse(await readFile(file, 'utf8'));
    assert.equal(doc.issue_title, ISSUE_TITLE);
    assert.match(doc.results.find(r => r.repo === 'zeta-stale' && r.check === 'archive/recent-activity').reason, /notice issue created in this run/);
    assert.ok(doc.results.every(r => r.check in doc.catalogue && r.reason));
    t.assert.snapshot({ ...doc, config_file: '<config>' });
  });

  it('--json --dry-run marks the planned archival', async () => {
    const file = path.join(tmpDir, 'out', 'archive_dry.json');
    await runArchive(['--dry-run', '--json', file]);
    const doc = JSON.parse(await readFile(file, 'utf8'));
    assert.deepEqual(doc.skipped[0], { repo: 'alpha-expired', reason: 'would be archived in this run (dry-run)' });
  });
});

describe('JSON output', () => {
  const catalogue = buildCatalogue({ warnAfter: '1 years', gracePeriod: '60 days', sha: 'abc' });

  it('documents both checks with the configured periods', () => {
    assert.deepEqual(Object.keys(catalogue), ['archive/recent-activity', 'archive/activity-checked']);
    assert.match(catalogue['archive/recent-activity'].documentation.short, /last 1 years.*archived 60 days later/);
    assert.equal(
      catalogue['archive/activity-checked'].documentation.url,
      'https://github.com/allianz/ospo/blob/abc/scripts/spec/archive_repos_spec.md#activity-checked',
    );
  });

  it('turns evaluated repos into results and the rest into skipped entries', () => {
    const evaluated = [
      { repo: 'active', pushedAt: '2026-10-30T10:00:00Z', stale: false },
      { repo: 'noticed', pushedAt: '2025-01-02T00:00:00Z', stale: true, newIssue: false, issueNumber: 12, daysLeft: 23 },
      { repo: 'new-notice', pushedAt: '2025-01-03T00:00:00Z', stale: true, newIssue: true, issueNumber: null, daysLeft: 60 },
      { repo: 'gone', pushedAt: '2024-01-01T00:00:00Z', stale: true, newIssue: false, issueNumber: 3, archived: true },
    ];
    const { results, skipped } = buildJsonResults({
      evaluated, neverPushed: ['empty'], archived: [{ name: 'old' }], excluded: [{ name: 'ospo' }], catalogue, warnAfter: '1 years',
    });
    assert.deepEqual(results.map(r => [r.repo, r.check, r.result, r.reason]), [
      ['active', 'archive/recent-activity', 'pass', 'Last push 2026-10-30, within the last 1 years'],
      ['active', 'archive/activity-checked', 'pass', 'Last push 2026-10-30'],
      ['noticed', 'archive/recent-activity', 'fail', 'Last push 2025-01-02, more than 1 years ago; notice issue #12, archival in 23 days'],
      ['noticed', 'archive/activity-checked', 'pass', 'Last push 2025-01-02; notice issue #12, archival in 23 days'],
      ['new-notice', 'archive/recent-activity', 'fail', 'Last push 2025-01-03, more than 1 years ago; notice issue created in this run, archival in 60 days'],
      ['new-notice', 'archive/activity-checked', 'pass', 'Last push 2025-01-03; notice issue created in this run, archival in 60 days'],
    ]);
    assert.deepEqual(skipped, [
      { repo: 'gone', reason: 'archived in this run' },
      { repo: 'empty', reason: 'no push activity yet' },
      { repo: 'old', reason: 'archived' },
      { repo: 'ospo', reason: 'excluded_repos' },
    ]);
  });
});
