#!/usr/bin/env node

// Writes the checks of GitHub guarantees that hold by design ("by construction").
// They test nothing and always pass, one result per active repository, so that the
// compliance report can count them like every other check. See spec/by_construction_spec.md.

import path from 'node:path';

import { parseCli, resolveToken, runIfMain } from './lib/cli.js';
import { defaultConfigPath, loadYaml } from './lib/config.js';
import { createGitHub, createOctokit } from './lib/github.js';
import { buildHeader, buildJsonDocument, checkResult, skippedRepos, specCatalogue, writeJsonReport } from './lib/json_output.js';
import { createLogger } from './lib/logger.js';
import { byName, partitionRepos } from './lib/repos.js';

// ── Constants ────────────────────────────────────────────────────────────────

export const TOOL = 'by_construction';
const SPEC_FILE = 'by_construction_spec.md';

/** The checks: catalogue name, rule and the reason written for every repository. */
export const CHECKS = {
  'by-construction/source-archives': {
    name: 'Source Archives',
    short: 'Not a test; always passes. Source archives of a release are generated by GitHub from the tag, so they contain exactly the repository content. Built release assets are not covered.',
    reason: 'Guaranteed by GitHub: source archives are generated from the tag',
  },
  'by-construction/sbom-available': {
    name: 'SBOM Available',
    short: 'Not a test; always passes. The dependency graph, and with it the SBOM, is always enabled for public repositories and cannot be switched off.',
    reason: 'Guaranteed by GitHub: the dependency graph is always enabled for public repositories',
  },
};

// ── Config ───────────────────────────────────────────────────────────────────

export async function loadConfig(configPath) {
  const config = (await loadYaml(configPath)) ?? {};
  config.excluded_repos = config.excluded_repos ?? [];
  return config;
}

// ── JSON output ──────────────────────────────────────────────────────────────

/** Catalogue entries without `fix`: project teams cannot fail these checks. */
export function buildCatalogue({ sha = null, env = {} } = {}) {
  const entry = specCatalogue(SPEC_FILE, { sha, env });
  return Object.fromEntries(Object.entries(CHECKS).map(([id, { name, short }]) => [id, entry(name, short)]));
}

/** One `pass` per check and active repository, sorted by repository; archived and excluded repositories are skipped. */
export function buildJsonResults({ active, archived, excluded, catalogue }) {
  const results = [...active].sort(byName).flatMap(repo =>
    Object.keys(catalogue).map(check => checkResult(repo.name, check, catalogue, { passed: true, reason: CHECKS[check].reason })),
  );
  return {
    results,
    skipped: [...skippedRepos(archived, 'archived'), ...skippedRepos(excluded, 'excluded_repos')],
  };
}

// ── Main ─────────────────────────────────────────────────────────────────────

export async function run({ argv = [], env = {}, logger, github, git, now = new Date() } = {}) {
  const { org, configPath, debug, json } = parseCli(argv, { defaultConfigPath: defaultConfigPath(TOOL), stringFlags: ['json'] });
  const gh = github ?? createGitHub(createOctokit(resolveToken(env)));
  const log = logger ?? createLogger({ debug });
  const config = await loadConfig(configPath);

  const { active, archived, excluded } = partitionRepos(await gh.listOrgRepos(org), config.excluded_repos);
  const names = repos => [...repos].sort(byName).map(r => r.name).join(', ');
  log.info(`Active repositories: ${active.length} (archived: ${archived.length}, excluded: ${excluded.length})`);
  log.debug(`Active repos: ${names(active)}`);
  if (archived.length > 0) log.debug(`Archived repos: ${names(archived)}`);
  if (excluded.length > 0) log.debug(`Excluded repos: ${names(excluded)}`);
  log.info(`Checks (always pass): ${Object.keys(CHECKS).join(', ')}`);

  if (json) {
    const header = await buildHeader({ tool: TOOL, org, configPath, issueTitle: null, env, now, git });
    const catalogue = buildCatalogue({ sha: header.ospo_sha, env });
    const doc = buildJsonDocument(header, { catalogue, ...buildJsonResults({ active, archived, excluded, catalogue }) });
    await writeJsonReport(path.resolve(json), doc);
    log.info(`\nJSON written to ${json}`);
  }
  return 0;
}

runIfMain(import.meta.url, run);
