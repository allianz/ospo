#!/usr/bin/env node

// Checks how the projects handle releases and security advisories, and writes the checks of
// GitHub guarantees that hold by design ("by construction"):
//   advisories/published-in-time   published security advisories were published in time
//   releases/versioning            release tags are SemVer/CalVer and increasing
//   releases/release-notes         every release has notes (body or CHANGELOG*)
//   by-construction/*              always pass, one per active repository
// JSON only: no issues, no writes to GitHub. See spec/process_check_spec.md.

import path from 'node:path';

import { ScriptError, parseCli, resolveToken, runIfMain } from './lib/cli.js';
import { mapWithConcurrency } from './lib/concurrency.js';
import { defaultConfigPath, loadYaml } from './lib/config.js';
import { parseRelativeDate } from './lib/dates.js';
import { createGitHub, createOctokit, isNotFound } from './lib/github.js';
import { buildHeader, buildJsonDocument, checkResult, skippedRepos, specCatalogue, writeJsonReport } from './lib/json_output.js';
import { createLogger } from './lib/logger.js';
import { byName, partitionRepos } from './lib/repos.js';

// ── Constants ────────────────────────────────────────────────────────────────

export const TOOL = 'process_check';
export const ADVISORIES = 'advisories/published-in-time';
export const VERSIONING = 'releases/versioning';
export const RELEASE_NOTES = 'releases/release-notes';
export const RELEASE_CHECKS = [VERSIONING, RELEASE_NOTES];
const SPEC_FILE = 'process_check_spec.md';
const CONCURRENCY = 8;
const MS_PER_DAY = 1000 * 60 * 60 * 24;
export const DEFAULTS = {
  advisories: { max_days: 90, lookback: '12 months' },
  releases: { lookback: '12 months', min_notes_chars: 50 },
};
const CHECK_LABELS = { [VERSIONING]: 'versioning', [RELEASE_NOTES]: 'release notes' };

/** The by-construction checks: catalogue name, rule and the reason written for every repository. */
export const BY_CONSTRUCTION = {
  'by-construction/source-archives': {
    name: 'Source Archives',
    short: 'Not a test; always passes. Source archives of a release are generated by GitHub from the tag, so they contain exactly the repository content. Built release assets are not covered.',
    reason: 'Guaranteed by GitHub: source archives are generated from the tag',
  },
  'by-construction/sbom-available': {
    name: 'SBOM Available',
    short: 'Not a test; always passes. The dependency graph, and with it the SBOM, is always enabled for public repositories and cannot be switched off.',
    reason: 'Guaranteed by GitHub: the dependency graph is always enabled for public repositories',
  },
};

export const ADVISORIES_NOT_READABLE = 'Security advisories not readable (request returned 404: private repository or missing permission)';
export const RELEASES_NOT_READABLE = 'Releases not readable (request returned 404: private repository or missing permission)';

const plural = (n, singular, pluralForm = `${singular}s`) => `${n} ${n === 1 ? singular : pluralForm}`;
const day = date => date.slice(0, 10);

// ── Config ───────────────────────────────────────────────────────────────────

export async function loadConfig(configPath) {
  const raw = (await loadYaml(configPath)) ?? {};
  const section = name => {
    const value = raw[name] ?? {};
    if (typeof value !== 'object' || Array.isArray(value)) throw new Error(`Config field ${name} must be a mapping (in ${configPath})`);
    return { ...DEFAULTS[name], ...value };
  };
  const config = { excluded_repos: raw.excluded_repos ?? [], advisories: section('advisories'), releases: section('releases') };
  for (const field of ['advisories.max_days', 'releases.min_notes_chars']) {
    const [name, key] = field.split('.');
    const value = config[name][key];
    if (!Number.isInteger(value) || value < 1) throw new Error(`Config field ${field} must be a positive integer (in ${configPath})`);
  }
  parseRelativeDate(config.advisories.lookback);
  parseRelativeDate(config.releases.lookback);
  return config;
}

// ── Advisories ───────────────────────────────────────────────────────────────

/**
 * Judges the advisories of one repository: those published since `since` must each have been
 * published at most `maxDays` days after their creation. No advisory in the window passes.
 */
export function evaluateAdvisories(advisories, { since, maxDays, lookback }) {
  const recent = advisories
    .filter(a => new Date(a.published_at) >= since)
    .map(a => ({
      id: a.ghsa_id,
      created: a.created_at,
      published: a.published_at,
      days: Math.floor((new Date(a.published_at) - new Date(a.created_at)) / MS_PER_DAY),
    }))
    .sort((a, b) => new Date(a.published) - new Date(b.published));

  if (recent.length === 0) return { passed: true, count: 0, reason: `No advisory published in the last ${lookback}`, details: [] };

  const late = recent.filter(a => a.days > maxDays);
  const after = a => `${a.id} after ${plural(a.days, 'day')}`;
  const advisoryCount = plural(recent.length, 'advisory', 'advisories');
  const reason = late.length === 0
    ? `${advisoryCount} published in the last ${lookback}: ${recent.map(after).join(', ')}`
    : `${late.length} of ${advisoryCount} published later than ${maxDays} days: ${late.map(after).join(', ')}`;
  const details = recent.map(a =>
    `${a.days > maxDays ? 'Warn' : 'Info'}: ${a.id} created ${day(a.created)}, published ${day(a.published)} (${plural(a.days, 'day')})`,
  );
  return { passed: late.length === 0, count: recent.length, reason, details };
}

// ── Releases: versions ───────────────────────────────────────────────────────

const IDENT = '[0-9A-Za-z-]+';
const VERSION_RE = new RegExp(`^v?(\\d+)\\.(\\d+)(?:\\.(\\d+))?(?:-(${IDENT}(?:\\.${IDENT})*))?(?:\\+${IDENT}(?:\\.${IDENT})*)?$`);

/**
 * Parses a SemVer or CalVer tag: an optional "v", two or three numeric parts, an optional
 * pre-release and optional build metadata (e.g. v1.2.3, 2026.11, 2026.11.0-rc.1).
 * A missing third part counts as 0. Returns null if the tag is neither.
 */
export function parseVersion(tag) {
  const match = VERSION_RE.exec(String(tag));
  if (!match) return null;
  const nums = [match[1], match[2], match[3] ?? '0'].map(Number);
  return { major: nums[0], nums, pre: match[4] ? match[4].split('.') : [] };
}

const isNumeric = id => /^\d+$/.test(id);

function comparePreIds(a, b) {
  if (isNumeric(a) && isNumeric(b)) return Number(a) - Number(b);
  if (isNumeric(a)) return -1;
  if (isNumeric(b)) return 1;
  return a < b ? -1 : a > b ? 1 : 0;
}

/** SemVer precedence of two parsed versions (< 0, 0, > 0). Build metadata is ignored. */
export function compareVersions(a, b) {
  for (let i = 0; i < 3; i++) if (a.nums[i] !== b.nums[i]) return a.nums[i] - b.nums[i];
  if (a.pre.length === 0 || b.pre.length === 0) return b.pre.length - a.pre.length;
  for (let i = 0; i < Math.min(a.pre.length, b.pre.length); i++) {
    const c = comparePreIds(a.pre[i], b.pre[i]);
    if (c !== 0) return c;
  }
  return a.pre.length - b.pre.length;
}

// ── Releases: checks ─────────────────────────────────────────────────────────

/** The published (not draft) releases published since `since`, oldest first. */
export function releasesInWindow(releases, since) {
  return releases
    .filter(r => !r.draft && r.published_at && new Date(r.published_at) >= since)
    .sort((a, b) => new Date(a.published_at) - new Date(b.published_at));
}

/**
 * Every tag is SemVer or CalVer, and within each major version line every release has a higher
 * version than all releases of that line published before it. `releases` is sorted by publication.
 */
export function evaluateVersioning(releases) {
  const tags = releases.map(r => r.tag_name);
  const invalid = [];
  const backwards = [];
  const highest = new Map(); // major → { version, release }
  for (const release of releases) {
    const version = parseVersion(release.tag_name);
    if (!version) {
      invalid.push(release);
      continue;
    }
    const top = highest.get(version.major);
    if (top && compareVersions(version, top.version) <= 0) backwards.push({ release, after: top.release, major: version.major });
    else highest.set(version.major, { version, release });
  }

  const details = [`Info: releases checked: ${tags.join(', ')}`];
  for (const r of invalid) details.push(`Warn: ${r.tag_name} (${day(r.published_at)}) is not SemVer or CalVer`);
  for (const b of backwards) {
    details.push(`Warn: ${b.release.tag_name} (${day(b.release.published_at)}) is not higher than ${b.after.tag_name} (${day(b.after.published_at)}) in major line ${b.major}`);
  }

  if (invalid.length === 0 && backwards.length === 0) {
    const subject = releases.length === 1 ? '1 release follows' : `${releases.length} releases follow`;
    return { passed: true, reason: `${subject} SemVer or CalVer, increasing within each major line`, details };
  }
  const parts = [];
  if (invalid.length > 0) parts.push(`${invalid.length} of ${plural(releases.length, 'release')} not SemVer or CalVer: ${invalid.map(r => r.tag_name).join(', ')}`);
  if (backwards.length > 0) {
    parts.push(`version not increasing: ${backwards.map(b => `${b.release.tag_name} after ${b.after.tag_name} in major line ${b.major}`).join(', ')}`);
  }
  return { passed: false, reason: parts.join('; '), details };
}

const bodyLength = release => (release.body ?? '').trim().length;

/** True if the release body alone is long enough to count as release notes. */
export const hasBodyNotes = (release, minChars) => bodyLength(release) >= minChars;

const escapeRegExp = s => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');

/** True if `text` mentions the version of `tag` (with or without "v"), not as part of a longer version. */
export function mentionsVersion(text, tag) {
  const version = String(tag).replace(/^v/, '');
  return new RegExp(`(?<![0-9A-Za-z.+-])v?${escapeRegExp(version)}(?![0-9A-Za-z+-]|\\.[0-9A-Za-z])`).test(text);
}

/**
 * Every release has notes: a body of at least `minChars` characters (trimmed), or its version is
 * mentioned in the changelog (`{ file, text }` or null). `releases` is sorted by publication.
 */
export function evaluateReleaseNotes(releases, { minChars, changelog = null }) {
  const judged = releases.map(r => {
    if (hasBodyNotes(r, minChars)) return { release: r, source: 'body' };
    if (changelog && mentionsVersion(changelog.text, r.tag_name)) return { release: r, source: 'changelog' };
    return { release: r, source: null };
  });
  const details = judged.map(({ release, source }) => {
    const length = bodyLength(release);
    if (source === 'body') return `Info: ${release.tag_name} release body (${plural(length, 'character')})`;
    if (source === 'changelog') return `Info: ${release.tag_name} mentioned in ${changelog.file}`;
    const where = changelog ? `not mentioned in ${changelog.file}` : 'no CHANGELOG file';
    return `Warn: ${release.tag_name} release body has ${plural(length, 'character')} (minimum ${minChars}), ${where}`;
  });

  const missing = judged.filter(j => !j.source);
  if (missing.length > 0) {
    return {
      passed: false,
      reason: `${missing.length} of ${plural(releases.length, 'release')} without notes: ${missing.map(j => j.release.tag_name).join(', ')}`,
      details,
    };
  }
  const source = judged.some(j => j.source === 'changelog') ? `release body or ${changelog.file}` : 'release body';
  const all = releases.length === 1 ? 'The release has' : `All ${releases.length} releases have`;
  return { passed: true, reason: `${all} notes (${source})`, details };
}

// ── JSON output ──────────────────────────────────────────────────────────────

/** All checks of the tool. The by-construction checks have no `fix`: project teams cannot fail them. */
export function buildCatalogue({ advisories = DEFAULTS.advisories, releases = DEFAULTS.releases, sha = null, env = {} } = {}) {
  const entry = specCatalogue(SPEC_FILE, { sha, env });
  return {
    [ADVISORIES]: entry(
      'Advisories Published in Time',
      `Every security advisory of the repository published in the last ${advisories.lookback} was published within ${advisories.max_days} days of its creation. Only published advisories are counted; they are public.`,
      `Project team with the OSPO: publish advisories within ${advisories.max_days} days of the report. A late publication counts for ${advisories.lookback}.`,
    ),
    ...Object.fromEntries(Object.entries(BY_CONSTRUCTION).map(([id, { name, short }]) => [id, entry(name, short)])),
    [VERSIONING]: entry(
      'Versioning',
      `Every release of the repository published in the last ${releases.lookback} has a SemVer or CalVer tag (optional "v" prefix), and within each major version line the versions increase with the release date. Not applicable without a release in that period.`,
      `Project team: tag releases with SemVer or CalVer (e.g. v1.4.2) and keep versions increasing within each major line. A release that breaks the rule counts for ${releases.lookback} unless its tag is corrected.`,
    ),
    [RELEASE_NOTES]: entry(
      'Release Notes',
      `Every release of the repository published in the last ${releases.lookback} has a release body of at least ${releases.min_notes_chars} characters, or a CHANGELOG file in the repository root mentions its version. Not applicable without a release in that period.`,
      'Project team: describe the functional and security changes in the GitHub release (or let GitHub generate the notes), or list the version in CHANGELOG.md. Editing an existing release fixes the finding.',
    ),
  };
}

/**
 * The results of the evaluated (active) repositories, sorted by repository and then in catalogue
 * order; archived and excluded repositories are skipped. A family that could not be read for a
 * repository (`{ error }`) gets one `errors` entry per check instead of results ("no data").
 */
export function buildJsonResults({ evaluated, archived, excluded, catalogue }) {
  const sorted = [...evaluated].sort((a, b) => a.repo.localeCompare(b.repo));
  const results = [];
  const errors = [];
  for (const { repo, advisories, releases } of sorted) {
    if (advisories.error) errors.push({ repo, check: ADVISORIES, reason: advisories.error });
    else results.push(checkResult(repo, ADVISORIES, catalogue, advisories));

    for (const [check, { reason }] of Object.entries(BY_CONSTRUCTION)) results.push(checkResult(repo, check, catalogue, { passed: true, reason }));

    if (releases.error) errors.push(...RELEASE_CHECKS.map(check => ({ repo, check, reason: releases.error })));
    else if (releases.na) results.push(...RELEASE_CHECKS.map(check => checkResult(repo, check, catalogue, { result: 'na', reason: releases.reason })));
    else results.push(checkResult(repo, VERSIONING, catalogue, releases.versioning), checkResult(repo, RELEASE_NOTES, catalogue, releases.notes));
  }
  return {
    results,
    skipped: [...skippedRepos(archived, 'archived'), ...skippedRepos(excluded, 'excluded_repos')],
    errors,
  };
}

// ── GitHub reads ─────────────────────────────────────────────────────────────

/** Returns `fn()`, or `fallback` if GitHub answers 404. */
async function unlessNotFound(fn, fallback) {
  try {
    return await fn();
  } catch (err) {
    if (isNotFound(err)) return fallback;
    throw err;
  }
}

/**
 * Runs the checks of one family for one repository. A 404 gives `{ error: notReadable }`; any other
 * error gives `{ error, unexpected: true }`, so that it does not stop the other families or repositories.
 */
async function family(fn, notReadable) {
  try {
    return await fn();
  } catch (err) {
    if (isNotFound(err)) return { error: notReadable };
    return { error: `Unexpected error: ${err.message}`, unexpected: true };
  }
}

/** The CHANGELOG* file in the repository root as `{ file, text }`, or null if there is none (or the repository is empty). */
export async function readChangelog(gh, org, repo) {
  const files = await unlessNotFound(() => gh.listRootFiles(org, repo), []);
  const file = files.filter(name => /^changelog/i.test(name)).sort()[0];
  if (!file) return null;
  const text = await unlessNotFound(() => gh.getFileText(org, repo, file), null);
  return text === null ? null : { file, text };
}

async function evaluateReleases(gh, org, repo, { since, lookback, min_notes_chars: minChars }) {
  const releases = releasesInWindow(await gh.listReleases(org, repo), since);
  if (releases.length === 0) return { na: true, reason: `No release in the last ${lookback}` };
  const changelog = releases.every(r => hasBodyNotes(r, minChars)) ? null : await readChangelog(gh, org, repo);
  return {
    count: releases.length,
    versioning: evaluateVersioning(releases),
    notes: evaluateReleaseNotes(releases, { minChars, changelog }),
  };
}

async function evaluateRepo(gh, org, repo, config) {
  const [advisories, releases] = await Promise.all([
    family(async () => evaluateAdvisories(await gh.listPublishedAdvisories(org, repo), config.advisories), ADVISORIES_NOT_READABLE),
    family(() => evaluateReleases(gh, org, repo, config.releases), RELEASES_NOT_READABLE),
  ]);
  return { repo, advisories, releases };
}

// ── Run log ──────────────────────────────────────────────────────────────────

function logNotReadable(log, evaluated, key) {
  const count = evaluated.filter(e => e[key].error).length;
  if (count > 0) log.info(`Not readable (in errors): ${plural(count, 'repository', 'repositories')}`);
}

function logAdvisories(log, evaluated, { since, maxDays }, debug) {
  log.info('Advisories:');
  log.debug(`Advisories published since ${since.toISOString()}, at most ${maxDays} days after creation`);
  for (const { repo, advisories: a } of evaluated) {
    if (a.error) log.info(`  ${repo}: ${a.error}`);
    else if (a.count > 0 || debug) log.info(`  ${repo}: ${a.reason}`);
  }
  const late = evaluated.filter(e => !e.advisories.error && !e.advisories.passed);
  log.info(late.length > 0 ? `Late publications: ${plural(late.length, 'repository', 'repositories')}` : 'All advisories published in time.');
  logNotReadable(log, evaluated, 'advisories');
}

function logReleases(log, evaluated, { since, min_notes_chars: minChars }, debug) {
  log.info('Releases:');
  log.debug(`Releases published since ${since.toISOString()}, release notes of at least ${minChars} characters`);
  for (const { repo, releases: r } of evaluated) {
    if (r.error) log.info(`  ${repo}: ${r.error}`);
    else if (r.na) {
      if (debug) log.info(`  ${repo}: ${r.reason}`);
    } else {
      for (const [check, outcome] of [[VERSIONING, r.versioning], [RELEASE_NOTES, r.notes]]) {
        if (!outcome.passed || debug) log.info(`  ${repo}: ${CHECK_LABELS[check]}: ${outcome.reason}`);
      }
    }
  }
  const releasing = evaluated.filter(e => !e.releases.error && !e.releases.na);
  const failing = releasing.filter(e => !e.releases.versioning.passed || !e.releases.notes.passed);
  log.info(`Releasing repositories: ${releasing.length}`);
  log.info(failing.length > 0 ? `Findings: ${plural(failing.length, 'repository', 'repositories')}` : 'All releases versioned and documented.');
  logNotReadable(log, evaluated, 'releases');
}

// ── Main ─────────────────────────────────────────────────────────────────────

export async function run({ argv = [], env = {}, logger, github, git, now = new Date() } = {}) {
  const { org, configPath, debug, json } = parseCli(argv, { defaultConfigPath: defaultConfigPath(TOOL, 'report'), stringFlags: ['json'] });
  if (!json) throw new ScriptError('--json is required');
  const gh = github ?? createGitHub(createOctokit(resolveToken(env)));
  const log = logger ?? createLogger({ debug });
  const config = await loadConfig(configPath);
  const windows = {
    advisories: { ...config.advisories, since: parseRelativeDate(config.advisories.lookback, now), maxDays: config.advisories.max_days },
    releases: { ...config.releases, since: parseRelativeDate(config.releases.lookback, now) },
  };

  const { active, archived, excluded } = partitionRepos(await gh.listOrgRepos(org), config.excluded_repos);
  log.info(`Active repositories: ${active.length} (archived: ${archived.length}, excluded: ${excluded.length})`);

  const evaluated = await mapWithConcurrency([...active].sort(byName), CONCURRENCY, repo => evaluateRepo(gh, org, repo.name, windows));

  logAdvisories(log, evaluated, windows.advisories, debug);
  logReleases(log, evaluated, windows.releases, debug);
  log.info(`By construction (always pass): ${Object.keys(BY_CONSTRUCTION).join(', ')}`);
  const unexpected = evaluated.flatMap(e => [e.advisories, e.releases]).filter(f => f.unexpected).length;
  if (unexpected > 0) log.info(`Unexpected errors (in errors): ${unexpected}`);

  const header = await buildHeader({ tool: TOOL, org, configPath, issueTitle: null, env, now, git });
  const catalogue = buildCatalogue({ advisories: config.advisories, releases: config.releases, sha: header.ospo_sha, env });
  const doc = buildJsonDocument(header, { catalogue, ...buildJsonResults({ evaluated, archived, excluded, catalogue }) });
  await writeJsonReport(path.resolve(json), doc);
  log.info(`\nJSON written to ${json}`);
  return unexpected > 0 ? 1 : 0;
}

runIfMain(import.meta.url, run);
